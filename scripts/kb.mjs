#!/usr/bin/env node
// Your local knowledge base (knowledge/ plus profile/).
//   index                 write knowledge/INDEX.md: every file with its title and headings
//   search <terms...>     rank files and show matching lines (all terms, case-insensitive)

import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { WORKSPACE, PATHS, parseArgs } from './lib/paths.mjs';

const TEXT = new Set(['.md', '.txt', '.markdown', '.yml', '.yaml', '.json', '.csv', '.tsv', '.eml', '.html']);
const MAX_BYTES = 2_000_000;

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.') || name === 'INDEX.md') continue;
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, out);
    else if (TEXT.has(extname(name).toLowerCase()) && st.size <= MAX_BYTES) out.push(full);
  }
  return out;
}

const files = () => [...walk(PATHS.knowledge), ...walk(join(WORKSPACE, 'profile'))];
const rel = (f) => relative(WORKSPACE, f).replace(/\\/g, '/');

const [cmd, ...rest] = process.argv.slice(2);
const args = parseArgs(rest);

if (cmd === 'index') {
  const lines = ['# Knowledge index', '', `Generated by \`job-agent kb index\`. ${files().length} files.`, ''];
  for (const f of walk(PATHS.knowledge)) {
    const text = readFileSync(f, 'utf8');
    const heads = [...text.matchAll(/^#{1,3}\s+(.+)$/gm)].map((m) => m[1].trim());
    const title = heads[0] ?? text.split(/\r?\n/).find((l) => l.trim())?.slice(0, 80) ?? '';
    lines.push(`- \`${rel(f)}\` — ${title}${heads.length > 1 ? `  \n  ${heads.slice(1, 8).join(' · ')}` : ''}`);
  }
  writeFileSync(join(PATHS.knowledge, 'INDEX.md'), lines.join('\n') + '\n');
  console.log(`Wrote knowledge/INDEX.md (${lines.length - 4} files)`);
} else if (cmd === 'search') {
  const terms = args._.map((t) => t.toLowerCase()).filter(Boolean);
  if (!terms.length) { console.error('search <terms...>'); process.exit(1); }
  const limit = Number(args.limit ?? 10);
  const hits = [];
  for (const f of files()) {
    const text = readFileSync(f, 'utf8');
    const low = text.toLowerCase();
    if (!terms.every((t) => low.includes(t))) continue;
    const score = terms.reduce((s, t) => s + low.split(t).length - 1, 0) + (terms.some((t) => rel(f).toLowerCase().includes(t)) ? 10 : 0);
    const lines = text.split(/\r?\n/).map((l, i) => [i + 1, l]).filter(([, l]) => terms.some((t) => l.toLowerCase().includes(t)));
    hits.push({ f, score, lines });
  }
  hits.sort((a, b) => b.score - a.score);
  if (!hits.length) console.log(`No file mentions all of: ${terms.join(', ')}`);
  for (const h of hits.slice(0, limit)) {
    console.log(`\n${rel(h.f)}  (${h.lines.length} matching lines)`);
    for (const [n, l] of h.lines.slice(0, 5)) console.log(`  ${String(n).padStart(4)}: ${l.trim().slice(0, 160)}`);
  }
  if (hits.length > limit) console.log(`\n…and ${hits.length - limit} more file(s). Use --limit.`);
} else {
  console.error('Usage: node scripts/kb.mjs index | search <terms...> [--limit n]');
  process.exit(1);
}
